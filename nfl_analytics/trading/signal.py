"""
Trade signal dataclass for prediction market strategies.

A Signal represents a strategy's desire to trade — it flows from the strategy
layer to the risk layer (for validation) to the execution layer (for submission).

Pipeline: MarketData → Strategy → Signal → RiskCheck → Execution → Order

Usage:
    from nfl_analytics.trading.signal import Signal
    from nfl_analytics.markets.base import Side

    signal = Signal(
        contract_id="KXNFL-26-AFC-KC",
        side=Side.YES,
        quantity=10,
        price_cents=62,
        edge_cents=7,
        model_prob=0.69,
        confidence=0.82,
        strategy="directional",
    )
    if signal.passes_threshold():
        order = signal.to_order()
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import UTC, datetime

from nfl_analytics.markets.base import Order, OrderType, Side


@dataclass
class Signal:
    """A trade signal generated by a strategy.

    Represents the strategy's assessment of an opportunity. Gets validated
    by the risk layer before conversion to an Order for execution.

    All prices in cents (1-99). edge_cents = model_prob_cents - contract_price_cents.
    """

    contract_id: str
    side: Side
    quantity: int
    price_cents: int  # Desired limit price (1-99)
    edge_cents: int  # model_prob_cents - market_price_cents
    model_prob: float  # Model's probability estimate (0.0-1.0)
    confidence: float  # Confidence in the estimate (0.0-1.0)
    strategy: str  # Strategy name that generated this signal
    market_id: str = ""
    sport: str = "nfl"
    meta_prob: float = 1.0  # Meta-labeling probability (trade quality filter)
    kelly_fraction: float = 0.0  # Optimal Kelly fraction (set by sizer)
    created_at: datetime = field(default_factory=lambda: datetime.now(UTC))

    @property
    def model_prob_cents(self) -> int:
        """Model probability in cents (same scale as contract price)."""
        return round(self.model_prob * 100)

    @property
    def edge_pct(self) -> float:
        """Edge as a percentage (e.g., 0.07 for 7 cents edge)."""
        return self.edge_cents / 100.0

    @property
    def expected_value_cents(self) -> float:
        """Expected value per contract in cents.

        EV = model_prob * payout - cost
        Payout for YES at price P = 100 - P (profit if event occurs)
        Cost = P (what you pay)
        EV = model_prob * 100 - P = edge_cents
        """
        return float(self.edge_cents)

    def passes_threshold(self, min_edge_cents: int = 3, min_confidence: float = 0.5) -> bool:
        """Check if signal meets minimum quality thresholds.

        Default thresholds:
        - Edge >= 3 cents (3% probability edge)
        - Confidence >= 50%
        """
        return self.edge_cents >= min_edge_cents and self.confidence >= min_confidence

    def to_order(self, order_id: str | None = None) -> Order:
        """Convert signal to an executable Order."""
        return Order(
            order_id=order_id or str(uuid.uuid4()),
            contract_id=self.contract_id,
            side=self.side,
            price_cents=self.price_cents,
            quantity=self.quantity,
            order_type=OrderType.LIMIT,
            strategy=self.strategy,
        )

    def __repr__(self) -> str:
        return (
            f"Signal({self.side.value} {self.quantity}x {self.contract_id} "
            f"@{self.price_cents}¢ edge={self.edge_cents}¢ "
            f"model={self.model_prob:.1%} conf={self.confidence:.1%} "
            f"strat={self.strategy})"
        )
