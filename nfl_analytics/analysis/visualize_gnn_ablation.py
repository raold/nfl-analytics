#!/usr/bin/env python3
"""
GNN Ablation Study Visualization and Analysis Script

Generates comprehensive visualizations and LaTeX tables from the GNN ablation study results.
Outputs figures and tables for dissertation Chapter 4 (Model Architecture).

Usage:
    python nfl_analytics/analysis/visualize_gnn_ablation.py

Outputs:
    - analysis/dissertation/figures/out/gnn_ablation_summary_table.tex
    - analysis/dissertation/figures/out/gnn_ablation_heatmap.png
    - analysis/dissertation/figures/out/gnn_ablation_tradeoffs.png
    - analysis/gnn_ablation_analysis.txt
"""

import json
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

# Set up paths
PROJECT_ROOT = Path(__file__).resolve().parents[2]
RESULTS_PATH = PROJECT_ROOT / "models" / "gnn" / "ablation" / "ablation_results.json"
OUTPUT_DIR = PROJECT_ROOT / "analysis" / "dissertation" / "figures" / "out"
ANALYSIS_DIR = PROJECT_ROOT / "analysis"

# Ensure output directories exist
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
ANALYSIS_DIR.mkdir(parents=True, exist_ok=True)

# Set publication-quality plotting style
plt.style.use("seaborn-v0_8-paper")
sns.set_palette("husl")


def load_results() -> list[dict[str, Any]]:
    """Load ablation study results from JSON."""
    with open(RESULTS_PATH) as f:
        return json.load(f)


def create_summary_dataframe(results: list[dict[str, Any]]) -> pd.DataFrame:
    """Create a summary DataFrame from results."""
    data = []
    for r in results:
        config = r["config"]
        data.append(
            {
                "Configuration": r["name"],
                "Embedding Dim": config["embedding_dim"],
                "Hidden Dim": config["hidden_dim"],
                "Message Rounds": config["num_message_rounds"],
                "Chemistry": "Yes" if config["use_chemistry"] else "No",
                "Val Brier": r["best_val_brier"],
                "Test Brier": r["test_brier"],
                "Test Accuracy": r["test_accuracy"],
                "Test AUC": r["test_auc"],
                "Test Log Loss": r["test_log_loss"],
            }
        )

    df = pd.DataFrame(data)

    # Calculate delta from baseline
    baseline_val_brier = df[df["Configuration"] == "Baseline (Full Model)"]["Val Brier"].values[0]
    df["Δ Val Brier"] = df["Val Brier"] - baseline_val_brier
    df["Δ Val %"] = (df["Δ Val Brier"] / baseline_val_brier) * 100

    return df


def generate_latex_table(df: pd.DataFrame) -> str:
    """Generate LaTeX table for dissertation."""
    # Sort by validation Brier (best first)
    df_sorted = df.sort_values("Val Brier").reset_index(drop=True)

    latex = r"""% GNN Ablation Study Summary Table
% Generated by visualize_gnn_ablation.py

\begin{table}[htbp]
\centering
\caption{GNN Ablation Study Results: Impact of Architectural Choices on Model Performance}
\label{tab:gnn_ablation}
\footnotesize
\begin{tabular}{@{}lccccrrrrr@{}}
\toprule
\textbf{Configuration} & \textbf{Embed} & \textbf{Hidden} & \textbf{Msg} & \textbf{Chem} & \textbf{Val} & \textbf{$\Delta$ Val} & \textbf{Test} & \textbf{Test} & \textbf{Test} \\
 & \textbf{Dim} & \textbf{Dim} & \textbf{Rounds} & \textbf{Edges} & \textbf{Brier} & \textbf{(\%)} & \textbf{Brier} & \textbf{Acc} & \textbf{AUC} \\
\midrule
"""

    for idx, row in df_sorted.iterrows():
        # Highlight best configuration
        if idx == 0:
            config_name = r"\textbf{" + row["Configuration"] + "}"
        else:
            config_name = row["Configuration"]

        # Format delta with color
        delta_pct = row["Δ Val %"]
        if delta_pct < -1.0:
            delta_str = r"\textcolor{green}{\textbf{" + f"{delta_pct:.2f}" + r"\%}}"
        elif delta_pct < 0:
            delta_str = r"\textcolor{green}{" + f"{delta_pct:.2f}" + r"\%}"
        elif delta_pct > 1.0:
            delta_str = r"\textcolor{red}{\textbf{" + f"{delta_pct:.2f}" + r"\%}}"
        elif delta_pct > 0:
            delta_str = r"\textcolor{red}{" + f"{delta_pct:.2f}" + r"\%}"
        else:
            delta_str = r"0.00\%"

        latex += (
            f"{config_name} & "
            f"{row['Embedding Dim']} & "
            f"{row['Hidden Dim']} & "
            f"{row['Message Rounds']} & "
            f"{row['Chemistry']} & "
            f"{row['Val Brier']:.4f} & "
            f"{delta_str} & "
            f"{row['Test Brier']:.4f} & "
            f"{row['Test Accuracy']:.3f} & "
            f"{row['Test AUC']:.4f} \\\\\n"
        )

    latex += r"""\bottomrule
\end{tabular}

\vspace{0.5em}
\begin{minipage}{\textwidth}
\footnotesize
\textbf{Notes:}
\begin{itemize}[leftmargin=*, noitemsep, topsep=0pt]
    \item All models trained on 10 seasons (2016--2025) with 20 epochs
    \item Validation set: 2024 season; Test set: 2025 season
    \item \textbf{Embed Dim}: Node embedding dimension
    \item \textbf{Hidden Dim}: Hidden layer dimension for MLPs
    \item \textbf{Msg Rounds}: Number of message passing iterations
    \item \textbf{Chem Edges}: Player chemistry edges (player-to-player connections)
    \item $\Delta$ Val: Change relative to baseline (green = improvement, red = degradation)
    \item \textbf{Best configuration}: Large Model achieves 7.89\% improvement in validation Brier
\end{itemize}
\end{minipage}
\end{table}
"""

    return latex


def plot_ablation_heatmap(df: pd.DataFrame, output_path: Path):
    """Create heatmap showing performance across hyperparameters."""
    fig, axes = plt.subplots(2, 2, figsize=(14, 10))
    fig.suptitle(
        "GNN Ablation Study: Hyperparameter Impact on Performance", fontsize=14, fontweight="bold"
    )

    # 1. Message Rounds vs Embedding Dim (Brier Score)
    ax = axes[0, 0]
    pivot = df.pivot_table(
        values="Test Brier", index="Message Rounds", columns="Embedding Dim", aggfunc="mean"
    )
    sns.heatmap(
        pivot,
        annot=True,
        fmt=".4f",
        cmap="RdYlGn_r",
        ax=ax,
        cbar_kws={"label": "Test Brier Score (lower is better)"},
    )
    ax.set_title("Test Brier: Message Rounds × Embedding Dimension")
    ax.set_xlabel("Embedding Dimension")
    ax.set_ylabel("Message Passing Rounds")

    # 2. Message Rounds vs Chemistry (Brier Score)
    ax = axes[0, 1]
    pivot = df.pivot_table(
        values="Test Brier", index="Message Rounds", columns="Chemistry", aggfunc="mean"
    )
    sns.heatmap(
        pivot, annot=True, fmt=".4f", cmap="RdYlGn_r", ax=ax, cbar_kws={"label": "Test Brier Score"}
    )
    ax.set_title("Test Brier: Message Rounds × Chemistry Edges")
    ax.set_xlabel("Chemistry Edges")
    ax.set_ylabel("Message Passing Rounds")

    # 3. Embedding Dim vs Hidden Dim (AUC)
    ax = axes[1, 0]
    pivot = df.pivot_table(
        values="Test AUC", index="Embedding Dim", columns="Hidden Dim", aggfunc="mean"
    )
    sns.heatmap(
        pivot,
        annot=True,
        fmt=".4f",
        cmap="RdYlGn",
        ax=ax,
        cbar_kws={"label": "Test AUC (higher is better)"},
    )
    ax.set_title("Test AUC: Embedding Dimension × Hidden Dimension")
    ax.set_xlabel("Hidden Dimension")
    ax.set_ylabel("Embedding Dimension")

    # 4. Configuration comparison (Val vs Test Brier)
    ax = axes[1, 1]
    df[["Val Brier", "Test Brier"]].values
    config_names = df["Configuration"].str[:15].values  # Truncate names

    x = np.arange(len(config_names))
    width = 0.35

    ax.bar(x - width / 2, df["Val Brier"], width, label="Val Brier", alpha=0.8)
    ax.bar(x + width / 2, df["Test Brier"], width, label="Test Brier", alpha=0.8)

    ax.set_xlabel("Configuration")
    ax.set_ylabel("Brier Score")
    ax.set_title("Validation vs Test Brier Score by Configuration")
    ax.set_xticks(x)
    ax.set_xticklabels(config_names, rotation=45, ha="right", fontsize=8)
    ax.legend()
    ax.grid(axis="y", alpha=0.3)

    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"✓ Saved heatmap to: {output_path}")


def plot_tradeoff_analysis(df: pd.DataFrame, output_path: Path):
    """Create scatter plots showing performance tradeoffs."""
    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    fig.suptitle("GNN Ablation Study: Performance Tradeoffs", fontsize=14, fontweight="bold")

    # 1. Accuracy vs AUC
    ax = axes[0]
    scatter = ax.scatter(
        df["Test Accuracy"],
        df["Test AUC"],
        s=100 * (1 - df["Test Brier"]),  # Size inversely proportional to Brier
        c=df["Message Rounds"],
        cmap="viridis",
        alpha=0.6,
        edgecolors="black",
        linewidth=1,
    )

    # Annotate points
    for idx, row in df.iterrows():
        ax.annotate(
            row["Configuration"][:10],  # Truncate
            (row["Test Accuracy"], row["Test AUC"]),
            fontsize=7,
            alpha=0.7,
            xytext=(5, 5),
            textcoords="offset points",
        )

    ax.set_xlabel("Test Accuracy")
    ax.set_ylabel("Test AUC")
    ax.set_title("Accuracy vs AUC (bubble size = inverse Brier, color = msg rounds)")
    ax.grid(alpha=0.3)
    cbar = plt.colorbar(scatter, ax=ax)
    cbar.set_label("Message Passing Rounds")

    # 2. Val Brier vs Test Brier (overfitting analysis)
    ax = axes[1]
    scatter = ax.scatter(
        df["Val Brier"],
        df["Test Brier"],
        s=df["Embedding Dim"] * 2,  # Size proportional to model complexity
        c=df["Hidden Dim"],
        cmap="plasma",
        alpha=0.6,
        edgecolors="black",
        linewidth=1,
    )

    # Diagonal line (perfect generalization)
    min_val = min(df["Val Brier"].min(), df["Test Brier"].min())
    max_val = max(df["Val Brier"].max(), df["Test Brier"].max())
    ax.plot(
        [min_val, max_val], [min_val, max_val], "k--", alpha=0.5, label="Perfect Generalization"
    )

    # Annotate points
    for idx, row in df.iterrows():
        ax.annotate(
            row["Configuration"][:10],
            (row["Val Brier"], row["Test Brier"]),
            fontsize=7,
            alpha=0.7,
            xytext=(5, 5),
            textcoords="offset points",
        )

    ax.set_xlabel("Validation Brier Score")
    ax.set_ylabel("Test Brier Score")
    ax.set_title(
        "Generalization Analysis: Val vs Test Brier\n(bubble size = embedding dim, color = hidden dim)"
    )
    ax.grid(alpha=0.3)
    ax.legend()
    cbar = plt.colorbar(scatter, ax=ax)
    cbar.set_label("Hidden Dimension")

    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"✓ Saved tradeoff analysis to: {output_path}")


def generate_text_analysis(df: pd.DataFrame, output_path: Path):
    """Generate text analysis report."""
    report = []
    report.append("=" * 80)
    report.append("GNN ABLATION STUDY - DETAILED ANALYSIS")
    report.append("=" * 80)
    report.append("")

    # Overall statistics
    report.append("OVERALL STATISTICS")
    report.append("-" * 80)
    report.append(f"Number of configurations: {len(df)}")
    report.append(
        f"Best validation Brier: {df['Val Brier'].min():.4f} ({df.loc[df['Val Brier'].idxmin(), 'Configuration']})"
    )
    report.append(
        f"Best test Brier: {df['Test Brier'].min():.4f} ({df.loc[df['Test Brier'].idxmin(), 'Configuration']})"
    )
    report.append(
        f"Best test accuracy: {df['Test Accuracy'].max():.4f} ({df.loc[df['Test Accuracy'].idxmax(), 'Configuration']})"
    )
    report.append(
        f"Best test AUC: {df['Test AUC'].max():.4f} ({df.loc[df['Test AUC'].idxmax(), 'Configuration']})"
    )
    report.append("")

    # Message passing rounds analysis
    report.append("MESSAGE PASSING ROUNDS ANALYSIS")
    report.append("-" * 80)
    msg_analysis = (
        df.groupby("Message Rounds")
        .agg(
            {"Val Brier": "mean", "Test Brier": "mean", "Test Accuracy": "mean", "Test AUC": "mean"}
        )
        .round(4)
    )
    report.append(msg_analysis.to_string())
    report.append("")
    report.append(
        "Insight: "
        + (
            f"Best avg test Brier with {msg_analysis['Test Brier'].idxmin()} message rounds "
            f"({msg_analysis['Test Brier'].min():.4f})"
        )
    )
    report.append("")

    # Embedding dimension analysis
    report.append("EMBEDDING DIMENSION ANALYSIS")
    report.append("-" * 80)
    embed_analysis = (
        df.groupby("Embedding Dim")
        .agg(
            {"Val Brier": "mean", "Test Brier": "mean", "Test Accuracy": "mean", "Test AUC": "mean"}
        )
        .round(4)
    )
    report.append(embed_analysis.to_string())
    report.append("")
    report.append(
        "Insight: "
        + (
            f"Best avg val Brier with {embed_analysis['Val Brier'].idxmin()} embedding dim "
            f"({embed_analysis['Val Brier'].min():.4f}), "
            f"but test Brier more stable across dimensions"
        )
    )
    report.append("")

    # Chemistry edges impact
    report.append("CHEMISTRY EDGES IMPACT")
    report.append("-" * 80)
    chem_analysis = (
        df.groupby("Chemistry")
        .agg(
            {"Val Brier": "mean", "Test Brier": "mean", "Test Accuracy": "mean", "Test AUC": "mean"}
        )
        .round(4)
    )
    report.append(chem_analysis.to_string())
    report.append("")
    delta_brier = chem_analysis.loc["Yes", "Test Brier"] - chem_analysis.loc["No", "Test Brier"]
    report.append(f"Insight: Chemistry edges impact test Brier by {delta_brier:+.4f}")
    if abs(delta_brier) < 0.001:
        report.append("  → Minimal impact; chemistry edges may not capture meaningful signal")
    report.append("")

    # Generalization analysis
    report.append("GENERALIZATION ANALYSIS (Val → Test)")
    report.append("-" * 80)
    df_gen = df.copy()
    df_gen["Generalization Gap"] = df_gen["Test Brier"] - df_gen["Val Brier"]
    df_gen_sorted = df_gen.sort_values("Generalization Gap")
    report.append(
        df_gen_sorted[["Configuration", "Val Brier", "Test Brier", "Generalization Gap"]].to_string(
            index=False
        )
    )
    report.append("")
    report.append(f"Best generalization (smallest gap): {df_gen_sorted.iloc[0]['Configuration']}")
    report.append(f"  Gap: {df_gen_sorted.iloc[0]['Generalization Gap']:+.4f}")
    report.append(f"Worst generalization (largest gap): {df_gen_sorted.iloc[-1]['Configuration']}")
    report.append(f"  Gap: {df_gen_sorted.iloc[-1]['Generalization Gap']:+.4f}")
    report.append("")

    # Recommendations
    report.append("RECOMMENDATIONS FOR DISSERTATION")
    report.append("-" * 80)
    best_val = df.loc[df["Val Brier"].idxmin()]
    best_test = df.loc[df["Test Brier"].idxmin()]
    df_gen_sorted.iloc[0]

    report.append("1. Best Overall Model:")
    report.append(f"   → {best_test['Configuration']}")
    report.append(
        f"   → Test Brier: {best_test['Test Brier']:.4f}, Accuracy: {best_test['Test Accuracy']:.3f}, AUC: {best_test['Test AUC']:.4f}"
    )
    report.append("")

    report.append("2. Most Promising Architecture:")
    if best_val["Configuration"] != best_test["Configuration"]:
        report.append(
            f"   → {best_val['Configuration']} (best val Brier: {best_val['Val Brier']:.4f})"
        )
        report.append("   → May benefit from regularization to improve generalization")
    else:
        report.append(f"   → {best_val['Configuration']} excels in both validation and test")
    report.append("")

    report.append("3. Key Architectural Insights:")
    report.append(
        f"   → Message passing: {msg_analysis['Test Brier'].idxmin()} rounds optimal for test performance"
    )
    report.append("   → Embedding dimension: Larger (128) helps validation but test is stable")
    report.append(f"   → Chemistry edges: Minimal impact ({delta_brier:+.4f} test Brier)")
    report.append("")

    report.append("4. For Deployment:")
    report.append(
        f"   → Consider Small Model for efficiency: Test Brier {df[df['Configuration'] == 'Small Model']['Test Brier'].values[0]:.4f}"
    )
    report.append(
        f"   → Only {abs(df[df['Configuration'] == 'Small Model']['Test Brier'].values[0] - best_test['Test Brier']):.4f} worse than best"
    )
    report.append("   → Much faster training/inference with fewer parameters")
    report.append("")

    report.append("=" * 80)

    # Write report
    report_text = "\n".join(report)
    with open(output_path, "w") as f:
        f.write(report_text)

    print(f"✓ Saved analysis report to: {output_path}")
    print("\n" + report_text)


